from difflib import SequenceMatcher

from .normalizer import normalize_text


def similarity(a, b):

    return SequenceMatcher(
        None,
        normalize_text(a),
        normalize_text(b),
    ).ratio()


def detect_intent(
    message,
    language="en",
):

    normalized_message = normalize_text(
        message
    )

    if not normalized_message:
        return None, 0


    best_intent = None
    best_score = 0


    # =====================================================
    # LANGUAGES TO CHECK
    #
    # IMPORTANT:
    # Always check selected language first.
    #
    # We also check English because our quick buttons
    # intentionally remain in English:
    #
    # Book Ride
    # Ride Prices
    # Safety
    # QR Ticket
    # =====================================================

    languages_to_check = [
        language
    ]


    if language != "en":

        languages_to_check.append(
            "en"
        )


    # =====================================================
    # CHECK ALL INTENTS
    # =====================================================

    for intent_name, language_keywords in INTENTS.items():

        for current_language in languages_to_check:

            keywords = language_keywords.get(
                current_language,
                []
            )


            for keyword in keywords:

                normalized_keyword = normalize_text(
                    keyword
                )


                if not normalized_keyword:
                    continue


                # ==========================================
                # 1. EXACT MESSAGE
                # ==========================================

                if (
                    normalized_message
                    ==
                    normalized_keyword
                ):

                    score = 1000


                # ==========================================
                # 2. KEYWORD / PHRASE INSIDE MESSAGE
                # ==========================================

                elif (
                    normalized_keyword
                    in
                    normalized_message
                ):

                    score = (
                        500
                        +
                        len(
                            normalized_keyword.split()
                        )
                        * 50
                        +
                        len(
                            normalized_keyword
                        )
                    )


                # ==========================================
                # 3. FUZZY MATCH
                # ==========================================

                else:

                    ratio = similarity(
                        normalized_message,
                        normalized_keyword,
                    )


                    score = int(
                        ratio * 100
                    )


                    if score < 72:
                        continue


                # ==========================================
                # STORE BEST RESULT
                # ==========================================

                if score > best_score:

                    best_score = score

                    best_intent = (
                        intent_name
                    )


    return (
        best_intent,
        best_score,
    )